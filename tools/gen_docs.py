def cell(value) -> str:
    """A table cell.  A literal pipe would end the column, so escape it --
    which matters here because CLI argument syntax is full of them."""
    return str(value).replace("|", "\\|").replace("\n", " ")


def table(out: io.StringIO, headers: list[str], rows: list[list[str]]) -> None:
    out.write("| " + " | ".join(cell(h) for h in headers) + " |\n")
    out.write("| " + " | ".join("---" for _ in headers) + " |\n")
    for row in rows:
        out.write("| " + " | ".join(cell(c) for c in row) + " |\n")
    out.write("\n")


def enum_rows(enum, notes: dict[int, str] | None = None) -> list[list[str]]:
    notes = notes or {}
    seen: dict[int, str] = {}
    for member in enum:
        seen.setdefault(int(member), member.name)
    return [[str(value), f"`{name}`", notes.get(value, "")]
            for value, name in sorted(seen.items())]


def enum_doc(enum) -> str:
    """The enum's own one-line description, if it has one."""
    doc = inspect.getdoc(enum) or ""
    first = doc.split("\n\n")[0].replace("\n", " ").strip()
    # IntEnum supplies a generic docstring when the class has none.
    return "" if first.startswith("An enumeration") or "int" == first else first


def enum_table(out: io.StringIO, enum, notes: dict[int, str] | None = None,
                value_header: str = "Value") -> None:
    """Heading-free enum section: its docstring, then its members."""
    doc = enum_doc(enum)
    if doc:
        out.write(doc + "\n\n")
    table(out, [value_header, "Name", "Notes"], enum_rows(enum, notes))


