"""Generate the reference documentation from the code.

Three documents come out of here, and all three are derived rather than
written, so they cannot drift from the implementation:

    docs/REFERENCE.md  the DOCSIS tables -- message types, IUCs, every TLV
                       namespace, timers -- read straight out of consts.py,
                       plus the channel and timing arithmetic evaluated for
                       the default lab
    docs/CLI.md        every `docsis` subcommand (from the argparse tree) and
                       every CMTS shell command (from the Cli command table)
    docs/API.md        a module map built from the package's own docstrings

`tests/test_docs.py` regenerates them into a temporary directory and fails if
anything differs, so a change to the code that should have changed the docs
does not slip through.

    ./docsis docs            # regenerate in place
    ./docsis docs --check    # fail if they are stale
"""

