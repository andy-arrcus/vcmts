def cli_doc() -> str:
    from docsislab.__main__ import build_parser
    from docsislab.cmts.cli import Cli
    from docsislab.lab.runner import Lab, LabOptions
    from docsislab.lab.topology import Topology

    out = io.StringIO()
    w = out.write
    w("# Command reference\n\n")
    w(GENERATED + "\n\n")
    w("Two command sets: the `docsis` program that runs and inspects a lab, "
      "and the CMTS-style shell you get inside `docsis cli`.\n\n")

    parser = build_parser()
    sub = next(a for a in parser._actions
               if isinstance(a, argparse._SubParsersAction))

    w("## `docsis`\n\n")
    table(out, ["Subcommand", "Purpose"],
          [[f"`{name}`", (p.description or "").strip().split("\n")[0]
            or sub._choices_actions[i].help or ""]
           for i, (name, p) in enumerate(sub.choices.items())])

    for name, sp in sub.choices.items():
        w(f"### `docsis {name}`\n\n")
        helps = {a.dest: a for a in sub._choices_actions}
        summary = helps[name].help if name in helps else ""
        if summary:
            w(f"{summary[0].upper()}{summary[1:]}.\n\n")
        usage = sp.format_usage().replace("usage: ", "").strip()
        w("```\n" + usage + "\n```\n\n")
        rows = []
        for action in sp._actions:
            if action.dest == "help" or action.dest == "func":
                continue
            flags = ", ".join(f"`{o}`" for o in action.option_strings) \
                or f"`<{action.dest}>`"
            default = ""
            if action.default not in (None, False) and action.option_strings:
                default = f"`{action.default}`"
            choices = ", ".join(f"`{c}`" for c in action.choices) \
                if action.choices else ""
            rows.append([flags, (action.help or "").strip(), choices, default])
        if rows:
            table(out, ["Option", "Meaning", "Choices", "Default"], rows)

    # -- the CMTS shell -------------------------------------------------
    lab = Lab(Topology(), LabOptions(speed=0.0, capture_path=None, echo=False))
    cli = Cli(lab)
    w("## The CMTS shell\n\n")
    w("Inside `docsis cli`. Unambiguous abbreviations work, so `sh ca mo` is "
      "`show cable modem`. A single command can also be run without attaching "
      "an interactive shell:\n\n")
    w("```sh\n./docsis cli show cable modem\n```\n\n")

    groups: dict[str, list] = {}
    for cmd in cli.commands:
        if cmd.words == ("?",):
            continue
        key = {"show": "Inspecting", "clear": "Acting",
               "test": "Acting", "ping": "Acting",
               "debug": "Acting"}.get(cmd.words[0], "Other")
        groups.setdefault(key, []).append(cmd)
    for key in ("Inspecting", "Acting", "Other"):
        if key not in groups:
            continue
        w(f"### {key}\n\n")
        table(out, ["Command", "Purpose"],
              [[f"`{' '.join(c.words)}" + (f" {c.args}" if c.args else "") + "`",
                c.help] for c in groups[key]])
    lab.close()
    return out.getvalue()


