DOCUMENTS = {
    "REFERENCE.md": reference,
    "CLI.md": cli_doc,
    "API.md": api_doc,
    "README.md": index_doc,
}


def generate() -> dict[str, str]:
    return {name: fn() for name, fn in DOCUMENTS.items()}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the reference docs.")
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if the docs on disk are stale")
    ap.add_argument("--out", default=str(DOCS))
    args = ap.parse_args(argv)

    target = pathlib.Path(args.out)
    target.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, text in generate().items():
        path = target / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
            continue
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT) if target == DOCS else path} "
              f"({len(text.splitlines())} lines)")
    if args.check:
        if stale:
            print("stale documentation: " + ", ".join(stale), file=sys.stderr)
            print("run ./docsis docs to regenerate", file=sys.stderr)
            return 1
        print("documentation is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
