def first_sentence(doc: str | None) -> str:
    if not doc:
        return ""
    text = inspect.cleandoc(doc).split("\n\n")[0].replace("\n", " ").strip()
    return text


def api_doc() -> str:
    out = io.StringIO()
    w = out.write
    w("# Module map\n\n")
    w(GENERATED + "\n\n")
    w("What lives where, from the package's own docstrings. The one structural "
      "rule worth stating: the CMTS and the cable modems hold no reference to "
      "each other. Everything between them goes through `phy.plant`, which is "
      "what keeps the simulation honest -- if a modem gets online, it did so "
      "by exchanging real DOCSIS frames.\n\n")

    modules = sorted(p for p in ROOT.glob("docsislab/**/*.py")
                     if p.name != "__init__.py")
    by_package: dict[str, list[pathlib.Path]] = {}
    for path in modules:
        package = ".".join(path.relative_to(ROOT).parts[:-1])
        by_package.setdefault(package, []).append(path)

    for package in sorted(by_package):
        w(f"## `{package}`\n\n")
        blurb = PACKAGE_BLURB.get(package)
        if blurb:
            w(blurb + "\n\n")
        for path in sorted(by_package[package]):
            tree = ast.parse(path.read_text(), str(path))
            module_doc = first_sentence(ast.get_docstring(tree))
            rel = path.relative_to(ROOT)
            lines = len(path.read_text().splitlines())
            w(f"### `{rel}`\n\n")
            if module_doc:
                w(f"{module_doc}\n\n")
            rows = []
            plain: list[str] = []
            for node in tree.body:
                if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
                    kind = "class"
                elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) \
                        and not node.name.startswith("_"):
                    kind = "function"
                else:
                    continue
                purpose = first_sentence(ast.get_docstring(node))
                if purpose:
                    rows.append([f"`{node.name}`", kind, purpose])
                else:
                    plain.append(node.name)
            if rows:
                table(out, ["Name", "Kind", "Purpose"], rows)
            if plain:
                # Self-describing helpers, listed rather than tabulated with
                # an empty column.
                w("Also: " + ", ".join(f"`{n}`" for n in plain) + ".\n\n")
            if not rows and not plain:
                w(f"{lines} lines.\n\n")
    return out.getvalue()


